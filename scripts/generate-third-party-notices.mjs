import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import process from 'node:process';

const bundledDependencies = [
  { name: 'jsonc-parser', licenseFile: 'LICENSE.md' },
  { name: 'yaml', licenseFile: 'LICENSE' },
];

const sections = [];
for (const dependency of bundledDependencies) {
  const packageDirectory = resolve('node_modules', dependency.name);
  const manifest = JSON.parse(
    await readFile(resolve(packageDirectory, 'package.json'), 'utf8'),
  );
  const license = (await readFile(
    resolve(packageDirectory, dependency.licenseFile),
    'utf8',
  ))
    .replaceAll('\r\n', '\n')
    .trim();
  sections.push(
    `${dependency.name} ${manifest.version}\nLicense: ${manifest.license}\n\n${license}`,
  );
}

const contents = `THIRD-PARTY SOFTWARE NOTICES AND INFORMATION

Downstream Canary's committed JavaScript bundles contain the dependencies
listed below. This file is generated by scripts/generate-third-party-notices.mjs.

${sections.join('\n\n----------------------------------------------------------------------\n\n')}
`;

const target = resolve('THIRD_PARTY_NOTICES');
if (process.argv.includes('--check')) {
  const actual = await readFile(target, 'utf8').catch(() => '');
  if (actual !== contents) {
    throw new Error(
      'THIRD_PARTY_NOTICES is missing or does not match bundled dependency metadata.',
    );
  }
} else {
  await writeFile(target, contents, 'utf8');
}
